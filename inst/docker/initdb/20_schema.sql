-- =============================================================================
-- Schema PostgreSQL/PostGIS/TimescaleDB per la variabile `db` di spatiotemporal
--
--   R (data(db))          PostgreSQL
--   ------------------    ------------------------------------------------
--   db$operator           operator
--   db$project            project
--   db$provider           provider
--   db$action             action      -> operator, project
--   db$p   (sf POINT)     p           -> provider ; geom geometry(Point,4326)
--   db$variable           variable    -> provider
--   db$attribute          attribute
--   db$ts  (long format)  ts          -> p, variable, attribute, action
--                                        HYPERTABLE TimescaleDB su timestamptz
--
-- Le colonne "ID" di R diventano "id" (minuscolo, niente virgolette in SQL).
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- ---------------------------------------------------------------- anagrafiche
CREATE TABLE operator (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    firstname  text,
    lastname   text,
    email      text
);

CREATE TABLE project (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE
);

CREATE TABLE provider (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE
);

CREATE TABLE action (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description  text,
    timestamptz  timestamptz NOT NULL DEFAULT now(),
    operator_id  integer REFERENCES operator(id),
    project_id   integer REFERENCES project(id)
);

-- ------------------------------------------------- punti / stazioni (sf POINT)
CREATE TABLE p (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name2        text,
    description  text,
    provider_id  integer REFERENCES provider(id),
    geom         geometry(Point, 4326) NOT NULL
);
CREATE INDEX p_geom_gix     ON p USING gist (geom);
CREATE INDEX p_provider_idx ON p (provider_id);

-- ------------------------------------------------------- variabili e attributi
CREATE TABLE variable (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL,
    description  text,
    provider_id  integer REFERENCES provider(id),
    UNIQUE (provider_id, name)
);

CREATE TABLE attribute (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text NOT NULL,
    description    text,
    variable_name  text
);

-- ------------------------------------------------ serie temporali (hypertable)
-- In una hypertable ogni vincolo UNIQUE/PK deve contenere la colonna temporale:
-- la chiave naturale (variable_id, p_id, timestamptz) è unica nel dataset GSOD.
-- L'"ID" di R è conservato come colonna id (con sequenza) ma non è PK.
CREATE SEQUENCE ts_id_seq AS bigint;

CREATE TABLE ts (
    id            bigint NOT NULL DEFAULT nextval('ts_id_seq'),
    attribute_id  integer REFERENCES attribute(id),
    variable_id   integer NOT NULL REFERENCES variable(id),
    timestamptz   timestamptz NOT NULL,
    p_id          integer NOT NULL REFERENCES p(id),
    value         double precision,
    attrvalue     text,
    action_id     integer REFERENCES action(id),
    PRIMARY KEY (variable_id, p_id, timestamptz)
);
ALTER SEQUENCE ts_id_seq OWNED BY ts.id;

-- Dati giornalieri dal 1960: chunk di 5 anni (~13 chunk, ~0.5-1 M righe ciascuno).
SELECT create_hypertable('ts', by_range('timestamptz', INTERVAL '5 years'));

CREATE INDEX ts_p_time_idx ON ts (p_id, timestamptz DESC);

-- Compressione colonnare: segmenti per (variabile, stazione), ordinati nel tempo.
-- Viene solo configurata qui; si attiva in 30_load_db.sh se STDB_COMPRESS=true.
ALTER TABLE ts SET (
    timescaledb.compress,
    timescaledb.compress_segmentby = 'variable_id, p_id',
    timescaledb.compress_orderby   = 'timestamptz'
);

-- ------------------------------------------------------------------------ viste
-- Stazioni con nome del provider e coordinate esplicite.
CREATE VIEW v_p AS
SELECT p.id, p.name2, p.description, p.provider_id, pr.name AS provider,
       ST_X(p.geom) AS lon, ST_Y(p.geom) AS lat, p.geom
FROM p
LEFT JOIN provider pr ON pr.id = p.provider_id;

-- Serie temporali "leggibili" (equivalente di get_ts() con i nomi).
CREATE VIEW v_ts AS
SELECT ts.timestamptz, ts.p_id, p.name2 AS station,
       ts.variable_id, v.name AS variable, ts.value,
       ts.attribute_id, a.name AS attribute, ts.attrvalue, ts.action_id
FROM ts
JOIN p        ON p.id = ts.p_id
JOIN variable v ON v.id = ts.variable_id
LEFT JOIN attribute a ON a.id = ts.attribute_id;

COMMENT ON TABLE ts IS 'Serie temporali in formato long (db$ts di spatiotemporal); hypertable TimescaleDB';
COMMENT ON TABLE p  IS 'Localizzazioni/stazioni (db$p, oggetto sf) in EPSG:4326';
